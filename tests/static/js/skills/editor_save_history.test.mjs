// A delayed save must not erase text typed while the request is in flight.
import assert from 'node:assert/strict';
import { after, test } from 'node:test';
import { installDom, waitFor } from '../_support/dom.mjs';
import { installFetchFake } from '../_support/fetchFake.mjs';
const dom = installDom();
const fake = installFetchFake();
after(async () => { fake.restore(); await dom.restore(); });
fake.route('GET', '/api/skills', () => ({ skills: [{ name: 'write-guide', status: 'draft' }] }));
fake.route('GET', '/api/skills/catalog', () => ({ skills: [] }));
fake.route('GET', '/api/skills/write-guide/markdown', () => ({ markdown: 'Original', version: 'v1' }));
document.body.innerHTML = '<div id="toast"></div><div class="admin-card"><div id="skills-list"></div></div>';
const { loadSkills } = await import('../../../../static/js/skills.js');
const input = (ta, value) => { ta.value = value; ta.dispatchEvent(new Event('input', { bubbles: true })); };
test('undo restores edits and a successful in-flight save preserves newer typing with the returned version', async () => {
  await loadSkills();
  const card = document.querySelector('.skill-card');
  card.querySelector('.skill-card-name').click();
  await waitFor(() => card._mdLoaded, { what: 'markdown loaded' });
  [...card.querySelectorAll('.doclib-card-action-btn')].find(b => b.textContent === 'Edit').click();
  const ta = card.querySelector('.skill-md-editor');
  const undo = card.querySelector('.skill-md-undo');
  assert.ok(undo, 'visible Undo control');
  assert.equal(undo.disabled, true);
  input(ta, 'First draft');
  input(ta, 'Second draft');
  undo.click();
  assert.equal(ta.value, 'First draft');
  let complete;
  const bodies = [];
  fake.route('POST', '/api/skills/write-guide/markdown', ({body}) => {
    bodies.push(JSON.parse(body));
    return new Promise(resolve => { complete = resolve; });
  });
  card.querySelector('.skill-md-save').click();
  await waitFor(() => complete, { what: 'save request' });
  assert.equal(card.querySelector('.skill-md-status').textContent, 'Saving…');
  input(ta, 'Newer typing');
  complete({ markdown: 'First draft', version: 'v2' });
  await waitFor(() => !card.querySelector('.skill-md-save').disabled, { what: 'saved snapshot' });
  assert.equal(ta.value, 'Newer typing');
  assert.equal(ta.dataset.original, 'First draft');
  assert.equal(card.querySelector('.skill-md-status').textContent, 'Unsaved changes');
  card.querySelector('.skill-md-save').click();
  await waitFor(() => bodies.length === 2, { what: 'second save' });
  assert.equal(bodies[1].version, 'v2');
  complete({ version: 'v3' });
  await waitFor(() => card.querySelector('.skill-md-status').textContent === 'Saved', { what: 'clean editor' });
  assert.equal(ta.value, 'Newer typing');
  input(ta, 'Keep this after a conflict');
  card.querySelector('.skill-md-save').click();
  await waitFor(() => bodies.length === 3, { what: 'conflicting save' });
  complete(new Response(JSON.stringify({ detail: 'Changed on another device' }), { status: 409, headers: { 'Content-Type': 'application/json' } }));
  await waitFor(() => card.querySelector('.skill-md-status').dataset.state === 'error', { what: 'visible error' });
  assert.equal(ta.value, 'Keep this after a conflict');
  assert.equal(card.querySelector('.skill-md-save').disabled, false);
  assert.equal(ta.dataset.original, 'Newer typing');
});
